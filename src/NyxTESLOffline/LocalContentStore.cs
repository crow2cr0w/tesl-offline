        internal bool SetSelectedCardBack(string json)
        {
            string category;
            string itemKey;
            if (!TryReadStringField(json, "category", out category) || category != "cardback" ||
                !TryReadStringField(json, "itemKey", out itemKey) || !IsKnownCardBack(itemKey))
                return false;

            lock (_sync)
            {
                _selectedCardBack = itemKey;
                PersistSelectedCardBack();
            }
            Plugin.Log("selected local card back: " + itemKey);
            return true;
        }

        internal string BuildInventoryResponse()
        {
            lock (_sync)
            {
                if (String.IsNullOrEmpty(_inventorySeedWithAlternates))
                    _inventorySeedWithAlternates = AddRetailAlternateArt(_inventorySeed);

                if (_decks.Count == 0)
                    return _inventorySeedWithAlternates;

                const string marker = "\"decks\":[]";
                int index = _inventorySeedWithAlternates.IndexOf(marker, StringComparison.Ordinal);
                if (index < 0)
                    throw new IOException("inventory seed has no empty decks array");

                StringBuilder deckArray = new StringBuilder();
                bool first = true;
                foreach (KeyValuePair<long, string> item in _decks)
                {
                    if (!first)
                        deckArray.Append(',');
                    deckArray.Append(item.Value);
                    first = false;
                }

                string replacement = "\"decks\":[" + deckArray.ToString() + "]";
                return _inventorySeedWithAlternates.Substring(0, index) + replacement +
                    _inventorySeedWithAlternates.Substring(index + marker.Length);
            }
        }

        private static string AddRetailAlternateArt(string seed)
        {
            StringBuilder additions = new StringBuilder();
            int count = 0;
            int i;
            for (i = 0; i < AlternateArts.Length; ++i)
            {
                AlternateArt art = AlternateArts[i];
                string baseEntry = FindCardTypeEntry(seed, art.BaseTypeHash);
                if (String.IsNullOrEmpty(baseEntry))
                    throw new IOException("alternate art base missing from local inventory: " +
                        art.TypeName + " -> " + art.BaseTypeHash);

                string entry = ReplaceJsonNumber(baseEntry, "typeHash", art.TypeHash);
                entry = ReplaceJsonString(entry, "typeName", art.TypeName);
                entry = ReplaceJsonString(entry, "exportCode", art.ExportCode);
                entry = ReplaceJsonNumber(entry, "alternateOfCardTypeHash", art.BaseTypeHash);
                if (additions.Length > 0)
                    additions.Append(',');
                additions.Append(entry);
                count += 1;
            }

            if (count == 0)
            {
                Plugin.Warn("retail CardCollection contained no usable alternate art");
                return seed;
            }

            int cardTypesEnd = seed.LastIndexOf("]}", StringComparison.Ordinal);
            if (cardTypesEnd < 0)
                throw new IOException("inventory seed has no cardTypes terminator");

            Plugin.Log("inventory enabled retail alternate art: " + count + " card(s)");
            return seed.Substring(0, cardTypesEnd) + "," + additions.ToString() +
                seed.Substring(cardTypesEnd);
        }

        private static string FindCardTypeEntry(string json, int typeHash)
        {
            string needle = "\"typeHash\":" + typeHash.ToString() + ",";
            int marker = json.IndexOf(needle, StringComparison.Ordinal);
            if (marker < 0)
                return null;
            int start = json.LastIndexOf('{', marker);
            int end = json.IndexOf('}', marker);
            if (start < 0 || end < start)
                return null;
            return json.Substring(start, end - start + 1);
        }

        private static string ReplaceJsonNumber(
            string json, string field, int replacement)
        {
            string needle = "\"" + field + "\":";
            int start = json.IndexOf(needle, StringComparison.Ordinal);
            if (start < 0)
                throw new IOException("card seed field missing: " + field);
            start += needle.Length;
            int end = start;
            if (end < json.Length && json[end] == '-')
                end += 1;
            while (end < json.Length && Char.IsDigit(json[end]))
                end += 1;
            return json.Substring(0, start) + replacement.ToString() + json.Substring(end);
        }

        private static string ReplaceJsonString(
            string json, string field, string replacement)
        {
            string needle = "\"" + field + "\":\"";
            int start = json.IndexOf(needle, StringComparison.Ordinal);
            if (start < 0)
                throw new IOException("card seed field missing: " + field);
            start += needle.Length;
            int end = json.IndexOf('\"', start);
            if (end < 0)
                throw new IOException("unterminated card seed field: " + field);
            return json.Substring(0, start) + EscapeJson(replacement) + json.Substring(end);
        }

        private static string EscapeJson(string value)
        {
            if (String.IsNullOrEmpty(value))
                return String.Empty;
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

