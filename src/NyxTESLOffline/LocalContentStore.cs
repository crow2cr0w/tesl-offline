        private static void ValidateInventorySeed(string json)
        {
            if (String.IsNullOrEmpty(json) ||
                json.IndexOf("\"inventory\"", StringComparison.Ordinal) < 0 ||
                json.IndexOf("\"cardTypes\"", StringComparison.Ordinal) < 0 ||
                json.IndexOf("\"decks\":[]", StringComparison.Ordinal) < 0)
                throw new IOException("invalid inventory seed");
        }

        private static void ValidateCampaignSeed(string json)
        {
            if (String.IsNullOrEmpty(json) ||
                json.IndexOf("\"campaignDatas\"", StringComparison.Ordinal) < 0)
                throw new IOException("invalid campaign seed");
        }

        private void LoadDecks()
        {
            _decks.Clear();
            _nextDeckId = FirstDeckId;

            if (!File.Exists(_deckStatePath))
                return;

            string[] lines = File.ReadAllLines(_deckStatePath, Encoding.UTF8);
            int i;
            for (i = 0; i < lines.Length; ++i)
            {
                string line = lines[i];
                if (String.IsNullOrEmpty(line))
                    continue;

                int tab = line.IndexOf('\t');
                if (tab <= 0 || tab + 1 >= line.Length)
                    continue;

                long id;
                if (!Int64.TryParse(line.Substring(0, tab), out id) || id <= 0)
                    continue;

                try
                {
                    byte[] raw = Convert.FromBase64String(line.Substring(tab + 1));
                    string json = Encoding.UTF8.GetString(raw);
                    long bodyId;
                    if (!TryReadInt64Field(json, "id", out bodyId) || bodyId != id)
                        continue;

                    _decks[id] = json;
                    if (id >= _nextDeckId)
                        _nextDeckId = id + 1L;
                }
                catch (FormatException)
                {
                    continue;
                }
            }
        }

        private void PersistDecks()
        {
            Directory.CreateDirectory(_stateDirectory);
            string temporary = _deckStatePath + ".tmp";

            using (StreamWriter writer = new StreamWriter(
                temporary, false, new UTF8Encoding(false)))
            {
                foreach (KeyValuePair<long, string> item in _decks)
                {
                    string encoded = Convert.ToBase64String(
                        Encoding.UTF8.GetBytes(item.Value));
                    writer.Write(item.Key.ToString());
                    writer.Write('\t');
                    writer.Write(encoded);
                    writer.Write('\n');
                }
            }

            if (File.Exists(_deckStatePath))
                File.Delete(_deckStatePath);
            File.Move(temporary, _deckStatePath);
        }

