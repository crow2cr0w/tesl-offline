        internal bool MarkCampaignEventComplete(
            long campaignId,
            int chapterEventId,
            bool isMastery)
        {
            lock (_sync)
            {
                string key = CampaignProgressKey(campaignId, chapterEventId, isMastery);
                if (_completedCampaignEvents.Contains(key))
                    return true;

                string updated;
                if (!TrySetCampaignEventComplete(
                    _campaignSeed, campaignId, chapterEventId, isMastery, out updated))
                    return false;

                _campaignSeed = updated;
                _completedCampaignEvents.Add(key);
                SaveCampaignProgress();
                return true;
            }
        }

        private void LoadCampaignProgress()
        {
            if (!File.Exists(_campaignProgressPath))
                return;

            string[] rows = File.ReadAllLines(_campaignProgressPath);
            for (int i = 0; i < rows.Length; ++i)
            {
                string[] fields = rows[i].Split('\t');
                long campaignId;
                int eventId;
                int mastery;
                if (fields.Length != 3 ||
                    !Int64.TryParse(fields[0], out campaignId) ||
                    !Int32.TryParse(fields[1], out eventId) ||
                    !Int32.TryParse(fields[2], out mastery))
                    continue;

                string updated;
                bool isMastery = mastery != 0;
                if (TrySetCampaignEventComplete(
                    _campaignSeed, campaignId, eventId, isMastery, out updated))
                {
                    _campaignSeed = updated;
                    _completedCampaignEvents.Add(
                        CampaignProgressKey(campaignId, eventId, isMastery));
                }
            }
        }

        private void SaveCampaignProgress()
        {
            string temporary = _campaignProgressPath + ".tmp";
            string[] rows = new string[_completedCampaignEvents.Count];
            _completedCampaignEvents.CopyTo(rows);
            Array.Sort(rows, StringComparer.Ordinal);
            File.WriteAllLines(temporary, rows, new UTF8Encoding(false));
            if (File.Exists(_campaignProgressPath))
                File.Delete(_campaignProgressPath);
            File.Move(temporary, _campaignProgressPath);
        }

        private static string CampaignProgressKey(long campaignId, int eventId, bool isMastery)
        {
            return campaignId.ToString() + "\t" + eventId.ToString() + "\t" +
                (isMastery ? "1" : "0");
        }

        private static bool TrySetCampaignEventComplete(
            string json,
            long campaignId,
            int eventId,
            bool isMastery,
            out string updated)
        {
            updated = json;
            string campaignNeedle = "\"campaignId\":" + campaignId.ToString();
            int campaignValue = json.IndexOf(campaignNeedle, StringComparison.Ordinal);
            if (campaignValue < 0)
                return false;

            int campaignStart = json.LastIndexOf('{', campaignValue);
            int campaignEnd = FindJsonObjectEnd(json, campaignStart);
            if (campaignStart < 0 || campaignEnd < 0)
                return false;

            string eventNeedle = "\"chapterEventId\":" + eventId.ToString();
            int eventValue = json.IndexOf(eventNeedle, campaignValue, StringComparison.Ordinal);
            while (eventValue >= 0 && eventValue < campaignEnd)
            {
                int masteryField = json.LastIndexOf("\"isMastery\":", eventValue, StringComparison.Ordinal);
                if (masteryField >= campaignStart)
                {
                    int masteryValue = masteryField + "\"isMastery\":".Length;
                    bool eventMastery = json.IndexOf("true", masteryValue, StringComparison.Ordinal) == masteryValue;
                    if (eventMastery == isMastery)
                    {
                        int eventStart = json.LastIndexOf('{', eventValue);
                        int eventEnd = FindJsonObjectEnd(json, eventStart);
                        if (eventStart >= campaignStart && eventEnd > eventValue && eventEnd < campaignEnd)
                        {
                            string eventJson = json.Substring(eventStart, eventEnd - eventStart + 1);
                            const string incomplete = "\"isComplete\":false";
                            int completeIndex = eventJson.IndexOf(incomplete, StringComparison.Ordinal);
                            if (completeIndex >= 0)
                                eventJson = eventJson.Substring(0, completeIndex) +
                                    "\"isComplete\":true" +
                                    eventJson.Substring(completeIndex + incomplete.Length);
                            updated = json.Substring(0, eventStart) + eventJson +
                                json.Substring(eventEnd + 1);
                            return true;
                        }
                    }
                }
                eventValue = json.IndexOf(eventNeedle, eventValue + eventNeedle.Length, StringComparison.Ordinal);
            }
            return false;
        }

        private static int FindJsonObjectEnd(string json, int objectStart)
        {
            if (objectStart < 0 || objectStart >= json.Length || json[objectStart] != '{')
                return -1;

            int depth = 0;
            bool inString = false;
            bool escaped = false;
            for (int i = objectStart; i < json.Length; ++i)
            {
                char ch = json[i];
                if (inString)
                {
                    if (escaped) escaped = false;
                    else if (ch == '\\') escaped = true;
                    else if (ch == '"') inString = false;
                    continue;
                }
                if (ch == '"') inString = true;
                else if (ch == '{') depth++;
                else if (ch == '}' && --depth == 0) return i;
            }
            return -1;
        }

