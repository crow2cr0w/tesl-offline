        private static bool IsKnownCardBack(string value)
        {
            int i;
            for (i = 0; i < CardBacks.Length; ++i)
            {
                if (CardBacks[i] == value)
                    return true;
            }
            return false;
        }

        private static bool TryReadStringField(string json, string field, out string value)
        {
            value = null;
            if (String.IsNullOrEmpty(json) || String.IsNullOrEmpty(field))
                return false;

            string needle = "\"" + field + "\"";
            int index = json.IndexOf(needle, StringComparison.Ordinal);
            if (index < 0)
                return false;
            index += needle.Length;
            while (index < json.Length && Char.IsWhiteSpace(json[index]))
                index++;
            if (index >= json.Length || json[index++] != ':')
                return false;
            while (index < json.Length && Char.IsWhiteSpace(json[index]))
                index++;
            if (index >= json.Length || json[index++] != '\"')
                return false;

            int start = index;
            while (index < json.Length && json[index] != '\"' && json[index] != '\\')
                index++;
            if (index >= json.Length || json[index] != '\"')
                return false;
            value = json.Substring(start, index - start);
            return true;
        }

        internal static bool TryReadInt64Field(string json, string field, out long value)
        {
            value = 0L;
            if (String.IsNullOrEmpty(json) || String.IsNullOrEmpty(field))
                return false;

            string needle = "\"" + field + "\"";
            int index = json.IndexOf(needle, StringComparison.Ordinal);
            if (index < 0)
                return false;

            index += needle.Length;
            while (index < json.Length && Char.IsWhiteSpace(json[index]))
                index++;
            if (index >= json.Length || json[index] != ':')
                return false;
            index++;
            while (index < json.Length && Char.IsWhiteSpace(json[index]))
                index++;

            int start = index;
            if (index < json.Length && json[index] == '-')
                index++;
            while (index < json.Length && Char.IsDigit(json[index]))
                index++;
            if (index <= start)
                return false;

            return Int64.TryParse(json.Substring(start, index - start), out value);
        }
