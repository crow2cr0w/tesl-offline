        internal LocalContentStore()
        {
            /* Payload is embedded and loaded with Assembly.Load(byte[]), so its
             * Assembly.Location is empty. Anchor data files to the retail
             * Assembly-CSharp.dll location instead. */
            string assemblyDirectory = Path.GetDirectoryName(
                typeof(SPTESL.GameManager).Assembly.Location);
            if (String.IsNullOrEmpty(assemblyDirectory))
                assemblyDirectory = ".";

            string dataDirectory = Path.Combine(
                assemblyDirectory, "NyxTESLOffline-data");
            _seedInventoryPath = Path.Combine(dataDirectory, "inventory-seed.json");
            _seedCampaignsPath = Path.Combine(dataDirectory, "campaigns-seed.json");
            _seedTestDecksPath = Path.Combine(dataDirectory, "recovered-test-decks.state");

            _stateDirectory = Path.Combine(
                Application.persistentDataPath, "NyxTESLOffline-Public-v1");
            _deckStatePath = Path.Combine(_stateDirectory, "decks.state");
            _testDecksSeedMarkerPath = Path.Combine(
                _stateDirectory, "recovered-test-decks-seeded.state");
            _cardBackStatePath = Path.Combine(_stateDirectory, "cardback.state");
            _campaignProgressPath = Path.Combine(_stateDirectory, "campaigns.progress");
        }

        internal void Load()
        {
            _inventorySeed = ReadRequiredText(_seedInventoryPath);
            _campaignSeed = ReadRequiredText(_seedCampaignsPath);

            ValidateInventorySeed(_inventorySeed);
            ValidateCampaignSeed(_campaignSeed);

            Directory.CreateDirectory(_stateDirectory);
            LoadCampaignProgress();
            LoadDecks();
            SeedPublicationDecksOnce();
            LoadSelectedCardBack();

            Plugin.Log("content store ready: card seed + campaign seed loaded");
            Plugin.Log("deck state: " + _decks.Count + " persisted deck(s)");
            Plugin.Log("selected card back: " + _selectedCardBack);
        }

