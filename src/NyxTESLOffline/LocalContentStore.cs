        private void SeedRecoveredTestDecksOnce()
        {
            if (File.Exists(_testDecksSeedMarkerPath) &&
                File.ReadAllText(_testDecksSeedMarkerPath, Encoding.UTF8) ==
                    RecoveredTestDeckSeedVersion)
                return;

            int added = 0;
            if (File.Exists(_seedTestDecksPath))
            {
                string[] lines = File.ReadAllLines(_seedTestDecksPath, Encoding.UTF8);
                int i;
                for (i = 0; i < lines.Length; ++i)
                {
                    string line = lines[i];
                    int tab = line.IndexOf('\t');
                    if (tab <= 0 || tab + 1 >= line.Length)
                        continue;

                    long id;
                    if (!Int64.TryParse(line.Substring(0, tab), out id) || id <= 0)
                        continue;
                    try
                    {
                        string json = Encoding.UTF8.GetString(
                            Convert.FromBase64String(line.Substring(tab + 1)));
                        long bodyId;
                        if (!TryReadInt64Field(json, "id", out bodyId) ||
                            bodyId != id || _decks.ContainsKey(id))
                            continue;
                        _decks[id] = json;
                        if (id >= _nextDeckId)
                            _nextDeckId = id + 1L;
                        added += 1;
                    }
                    catch (FormatException)
                    {
                        continue;
                    }
                }
            }

            if (added > 0)
                PersistDecks();
            File.WriteAllText(
                _testDecksSeedMarkerPath, RecoveredTestDeckSeedVersion,
                new UTF8Encoding(false));
            if (added > 0)
                Plugin.Log("seeded recovered-card test decks=" + added);
        }

        private void RemoveRecoveredTestDecks()
        {
            int removed = 0;
            lock (_sync)
            {
                for (long id = 9000000000001L; id <= 9000000000009L; ++id)
                {
                    if (_decks.Remove(id))
                        ++removed;
                }
                if (removed > 0)
                    PersistDecks();
            }

            if (removed > 0)
                Plugin.Log("removed recovered test decks=" + removed);
        }

        internal string CreateDeck()
        {
            lock (_sync)
            {
                long id = _nextDeckId++;
                return "{\"deckId\":" + id.ToString() + "}";
            }
        }

        internal bool SaveDeck(string json)
        {
            if (String.IsNullOrEmpty(json))
                return false;

            long id;
            if (!TryReadInt64Field(json, "id", out id) || id <= 0)
                return false;

            lock (_sync)
            {
                _decks[id] = json.Trim();
                if (id >= _nextDeckId)
                    _nextDeckId = id + 1L;
                PersistDecks();
            }

            Plugin.Log("saved local deck id=" + id);
            return true;
        }

        internal bool DeleteDeck(string json)
        {
            long id;
            if (!TryReadInt64Field(json, "deckId", out id) || id <= 0)
                return false;

            bool removed;
            lock (_sync)
            {
                removed = _decks.Remove(id);
                if (removed)
                    PersistDecks();
            }

            if (removed)
                Plugin.Log("deleted local deck id=" + id);
            return removed;
        }

